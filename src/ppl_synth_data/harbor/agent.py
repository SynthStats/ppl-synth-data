"""Harbor agent owned by ppl-synth-data.

The agent is deliberately domain-side code: it calls an OpenAI-compatible LLM
endpoint, writes the submitted probabilistic program into the task sandbox, and
records strict ATIF-compatible generation metadata. SynthStats only names this
import path from its Harbor generator; it does not import this module.

This module is the thin Harbor `InstalledAgent` entry point: environment
parsing, program extraction, OpenAI response handling, tokenizer/EOS scoring,
and ATIF-record building live in the sibling `agent_*` modules (`agent_env`,
`agent_extraction`, `agent_openai`, `agent_tokenizer`, `agent_metadata`,
`agent_eos`, `agent_atif`, `agent_shared`); this file wires them together into
`SynthStatsInstalledAgent`. `export_skyrl_bundle.py` vendors this file plus
those sibling modules into a self-contained SkyRL bundle (see
`_flatten_bundled_agent_imports` there).
"""

from __future__ import annotations

import json
import logging
import os
import shlex
from collections.abc import Mapping
from pathlib import Path
from typing import Any, cast

from ppl_synth_data.harbor.agent_atif import (
    build_atif_record,
    build_messages,
    write_agent_result_log,
)
from ppl_synth_data.harbor.agent_env import (
    parse_bool_env,
    parse_json_env,
    require_llm_api_base,
    require_openai_api_key,
    runtime_from_task_config,
    submission_path_for_runtime,
)
from ppl_synth_data.harbor.agent_eos import (
    complete_subtb_generation_metadata,
    score_eos_logprobs_with_prompt_logprobs,
)
from ppl_synth_data.harbor.agent_extraction import (
    extract_submitted_program,
    write_submission_program,
    write_text_to_environment,
)
from ppl_synth_data.harbor.agent_metadata import extract_generation_metadata
from ppl_synth_data.harbor.agent_openai import build_openai_client, render_openai_message
from ppl_synth_data.harbor.agent_shared import _as_mapping, _first_choice
from ppl_synth_data.harbor.agent_tokenizer import _TOKENIZER_CACHE

logger = logging.getLogger(__name__)

try:
    from harbor.agents.base import BaseAgent as _BaseAgent
except ImportError:  # pragma: no cover - Harbor is optional in unit tests.
    _BaseAgent = None


def _make_agent_class() -> type[Any] | None:
    if _BaseAgent is None:
        return None

    base_cls = cast(type[Any], _BaseAgent)

    class SynthStatsInstalledAgent(base_cls):  # type: ignore[misc, valid-type]
        """Harbor-side agent for external task packages generated by ppl-synth-data."""

        SUPPORTS_ATIF = True

        @staticmethod
        def name() -> str:
            return "synthstats"

        def __init__(self, **kwargs: Any) -> None:
            extra_env = kwargs.pop("extra_env", None)
            self.collect_rollout_details = bool(kwargs.pop("collect_rollout_details", True))
            super().__init__(**kwargs)
            runtime_env = dict(os.environ)
            if isinstance(extra_env, Mapping):
                runtime_env.update({str(key): str(value) for key, value in extra_env.items()})
            self._runtime_env = runtime_env
            self.llm_api_base = require_llm_api_base(runtime_env)
            self.task_config = parse_json_env("TASK_CONFIG", env=runtime_env)
            self.task_provenance = parse_json_env("TASK_PROVENANCE", env=runtime_env)
            model_name = runtime_env.get("MODEL_NAME")
            if not model_name:
                raise ValueError("MODEL_NAME must be set for SynthStatsInstalledAgent")
            self.model = model_name
            self.require_eos_logprobs = parse_bool_env(
                "REQUIRE_EOS_LOGPROBS",
                env=runtime_env,
                default=False,
            )

        def version(self) -> str | None:
            return "ppl-synth-data"

        async def setup(self, environment: Any) -> None:
            runtime = runtime_from_task_config(self.task_config)
            submission_parent = submission_path_for_runtime(runtime).parent
            result = await environment.exec(
                command=(
                    "mkdir -p /logs/agent /logs/artifacts "
                    f"{shlex.quote(submission_parent.as_posix())} "
                    "&& chmod 777 /logs/agent /logs/artifacts"
                )
            )
            self._raise_failed_exec(result)

        async def exec_as_root(self, environment: Any, *, command: str) -> None:
            result = await environment.exec(command=command)
            self._raise_failed_exec(result)

        @staticmethod
        def _raise_failed_exec(result: Any) -> None:
            return_code = getattr(result, "return_code", 0)
            if return_code != 0:
                stderr = getattr(result, "stderr", "")
                raise RuntimeError(
                    f"Harbor sandbox command failed with exit code {return_code}: {stderr}"
                )

        async def run(self, instruction: str, environment: Any, context: Any) -> None:
            messages = build_messages(instruction, self.task_config)
            response = await self._create_chat_completion(messages)
            response_mapping = _as_mapping(response)
            if response_mapping is None:
                raise TypeError("LLM response must be mapping-like")
            choice = _first_choice(response_mapping)
            response_text = render_openai_message(choice)
            runtime = runtime_from_task_config(self.task_config)
            program = extract_submitted_program(response_text, runtime=runtime)
            submission_path = submission_path_for_runtime(runtime)
            await write_text_to_environment(
                self,
                environment,
                path=submission_path,
                text=program,
            )
            generation_metadata = extract_generation_metadata(
                response_mapping,
                model_name=self.model,
                response_text=response_text,
                prompt_messages=messages,
            )
            if self.require_eos_logprobs:
                generation_metadata = await complete_subtb_generation_metadata(
                    self._openai_client(),
                    model_name=self.model,
                    generation_metadata=generation_metadata,
                )
            atif = build_atif_record(
                messages=messages,
                response_text=response_text,
                generation_metadata=generation_metadata,
                task_config=self.task_config,
                task_provenance=self.task_provenance,
            )

            result = {
                "program": program,
                "language": runtime,
                "submission_path": str(submission_path),
                "task_config": self.task_config,
                "task_provenance": self.task_provenance,
                "trajectory": atif,
                **generation_metadata,
            }
            await write_text_to_environment(
                self,
                environment,
                path=Path("/logs/agent") / "synthstats_result.json",
                text=json.dumps(result, indent=2, sort_keys=True),
            )
            await write_text_to_environment(
                self,
                environment,
                path=Path("/logs/agent") / "trajectory.json",
                text=json.dumps(atif, indent=2, sort_keys=True),
            )
            await write_text_to_environment(
                self,
                environment,
                path=Path("/logs/artifacts") / "synthstats_result.json",
                text=json.dumps(result, indent=2, sort_keys=True),
            )
            await write_text_to_environment(
                self,
                environment,
                path=Path("/logs/artifacts") / "trajectory.json",
                text=json.dumps(atif, indent=2, sort_keys=True),
            )

            if context is not None:
                existing_metadata = getattr(context, "metadata", None)
                merged_metadata = (
                    dict(existing_metadata) if isinstance(existing_metadata, Mapping) else {}
                )
                merged_metadata.update(result)
                context.metadata = merged_metadata

        async def _create_chat_completion(self, messages: list[dict[str, str]]) -> Any:
            client = self._openai_client()
            return await client.chat.completions.create(
                model=self.model,
                messages=messages,
                temperature=float(self._runtime_env.get("TEMPERATURE", "0.7")),
                max_tokens=int(self._runtime_env.get("MAX_TOKENS", "300")),
                logprobs=True,
                extra_body={
                    "return_token_ids": True,
                    "return_eos_logprobs": True,
                    "chat_template_kwargs": {"enable_thinking": False},
                },
            )

        def _openai_client(self) -> Any:
            return build_openai_client(
                base_url=self.llm_api_base,
                api_key=require_openai_api_key(
                    self._runtime_env,
                    llm_api_base=self.llm_api_base,
                ),
            )

    return SynthStatsInstalledAgent


SynthStatsInstalledAgent = _make_agent_class()
HARBOR_AGENT_AVAILABLE = SynthStatsInstalledAgent is not None

